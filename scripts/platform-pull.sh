#!/usr/bin/env bash
#
# Write platform/<workspace>.env from the facts Terraform published to SSM.
#
#   scripts/platform-pull.sh <workspace> [prefix]
#   scripts/platform-pull.sh dev            # reads /platform/dev/*
#
# Terraform writes every fact this project needs to SSM Parameter Store, at
# <prefix>/<workspace>/<key>, in the same apply that changes it. This copies
# them into the file scripts/platform.sh reads, so they are fetched once — not
# once per make target, which is several AWS round trips per command.
#
# The file used to be pasted by hand from `terraform output`, and went stale on
# every apply that moved an address. Re-run this after any apply instead; it
# rewrites the file whole, so a key Terraform stopped publishing disappears too.
#
# Needs ssm:GetParametersByPath on <prefix>/<workspace>/ — nothing else, and
# no Terraform.

set -euo pipefail

WORKSPACE="${1:-}"
PREFIX="${2:-${PLATFORM_SSM_PREFIX:-/platform}}"
REGION="${AWS_REGION:-us-east-1}"

[[ -n "${WORKSPACE}" ]] || { echo "usage: $(basename "$0") <workspace> [ssm-prefix]" >&2; exit 1; }
command -v aws >/dev/null 2>&1 || { echo "error: the aws CLI is not installed" >&2; exit 1; }

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${ROOT}/platform/${WORKSPACE}.env"
path="${PREFIX}/${WORKSPACE}/"

# --recursive off: the facts sit directly under the path. Name and value per
# line, tab-separated — values never contain tabs, and this avoids needing jq.
if ! params="$(aws ssm get-parameters-by-path --path "${path}" --region "${REGION}" \
      --query 'Parameters[].[Name,Value]' --output text 2>&1)"; then
  echo "error: could not read ${path} from SSM in ${REGION}:" >&2
  echo "${params}" | sed 's/^/         /' >&2
  exit 1
fi

if [[ -z "${params}" ]]; then
  echo "error: nothing under ${path} in ${REGION}." >&2
  echo "       The infrastructure for '${WORKSPACE}' is not applied yet, or was applied" >&2
  echo "       with a different platform_ssm_prefix:" >&2
  echo "         make -C ../terraform apply WORKSPACE=${WORKSPACE}" >&2
  exit 1
fi

tmp="$(mktemp)"; trap 'rm -f "${tmp}"' EXIT
{
  echo "# Platform facts for ${WORKSPACE} — GENERATED by \`make platform-pull\` from"
  echo "# SSM ${path} on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit: re-run that"
  echo "# instead. Machine-specific overrides go in platform/${WORKSPACE}.local.env."
  echo
  while IFS=$'\t' read -r name value; do
    [[ -n "${name}" ]] || continue
    key="${name##*/}"
    printf '%s=%s\n' "${key^^}" "${value}"
  done <<< "${params}" | sort
} > "${tmp}"

mv "${tmp}" "${OUT}"
trap - EXIT

echo "==> wrote ${OUT#"${ROOT}/"} — $(grep -c '=' "${OUT}") facts from ${path}"
