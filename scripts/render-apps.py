"""Fill argocd/apps.example.yaml for one environment.

    python3 scripts/render-apps.py <template> <out> <automated:true|false> <team>...

Called by scripts/argocd-apps.sh, which exports every value as ARGO_<NAME>.
The PLATFORM section is emitted once, the TEAM section once per team. Fails
on any placeholder left unfilled, rather than applying a manifest that names
__REPO_URL__ as its git repository.
"""

import os
import re
import sys

template, out, automated = sys.argv[1], sys.argv[2], sys.argv[3] == "true"
teams = sys.argv[4:]
values = {k[len("ARGO_"):]: v for k, v in os.environ.items() if k.startswith("ARGO_")}

text = open(template).read()

# Split on the two section banners; everything before PLATFORM is the header
# comment, which documents the placeholders and is not emitted.
_, rest = text.split("# ─── PLATFORM ", 1)
platform, team = rest.split("# ─── TEAM ", 1)
platform = platform.split("\n", 1)[1]
team = team.split("\n", 1)[1]

block = "    automated:\n      prune: true\n      selfHeal: true\n" if automated else ""


def fill(section, extra):
    for key, val in {**values, **extra}.items():
        section = section.replace("__%s__" % key, val)
    # Anchored to the marker line exactly as it sits inside syncPolicy.
    section = section.replace("    # __AUTOMATED__\n", block)
    left = sorted(set(re.findall(r"__[A-Z_]+__", section)))
    if left:
        sys.exit("error: unfilled placeholders: %s" % " ".join(left))
    return section.strip("\n") + "\n"


docs = [fill(platform, {})] + [fill(team, {"TEAM": t}) for t in teams]

with open(out, "w") as f:
    f.write("# GENERATED by scripts/argocd-apps.sh — do not edit, re-render.\n")
    # Each TEAM section already opens with its own `---`; the PLATFORM one is
    # first in the file and needs none.
    f.write("".join(docs))
